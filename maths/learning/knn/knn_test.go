func TestKNN(t *testing.T) {
	labels := []int{}
	samples := [][]float64{}
	for _, sample := range TestTrainingSamples["cars"] {
		labels = append(labels, 1)
		samples = append(samples, sample[:])
	}
	for _, sample := range TestTrainingSamples["buses"] {
		labels = append(labels, 2)
		samples = append(samples, sample[:])
	}
	for _, sample := range TestTrainingSamples["trucks"] {
		labels = append(labels, 3)
		samples = append(samples, sample[:])
	}

	model := NewSimpleModel[float64](5)
	if err := model.Train(samples, labels); err != nil {
		t.Fatal(err)
	}

	getName := func(label int) string {
		switch label {
		case 1:
			return "car"
		case 2:
			return "bus"
		case 3:
			return "truck"
		default:
			return "未知类型: " + strconv.Itoa(label)
		}
	}

	for _, sample := range TestValidationSamples {
		label, err := model.Predict(sample[:])
		if err != nil {
			t.Fatal(err)
		}

		t.Log(sample, " >>> ", getName(label))
	}
}

// TestPredictInvalidK 验证近邻数量为零时返回哨兵错误，而不是在空堆上取值 panic
func TestPredictInvalidK(t *testing.T) {
	model := NewSimpleModel[float64](0)
	if err := model.Train([][]float64{{1, 2}}, []int{1}); err != nil {
		t.Fatalf("Train() error = %v", err)
	}

	if _, err := model.Predict([]float64{1, 2}); !errors.Is(err, ErrInvalidK) {
		t.Fatalf("Predict() error = %v, want %v", err, ErrInvalidK)
	}
}

